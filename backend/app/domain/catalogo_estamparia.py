def obter_embalagem_estamparia(material: str | None) -> str | None:
    if not material:
        return None
    if "/" in material:
        for parte in material.split("/"):
            res = obter_embalagem_estamparia(parte.strip())
            if res:
                return res
    mat_clean = re.sub(r"[^A-Za-z0-9]", "", material).upper()
    if mat_clean in CATALOGO_EMBALAGENS_ESTAMPARIA:
        return CATALOGO_EMBALAGENS_ESTAMPARIA[mat_clean]
    if len(mat_clean) >= 8:
        pref = mat_clean[:8]
        for k, v in CATALOGO_EMBALAGENS_ESTAMPARIA.items():
            if k.startswith(pref):
                return v
    # Variação sem dígito intermediário (ex: H0316EB6 -> H03161EB6A)
    m = re.match(r"^([A-Z]\d{4,5})([A-Z].*)$", mat_clean)
    if m:
        base, suffix = m.groups()
        for k, v in CATALOGO_EMBALAGENS_ESTAMPARIA.items():
            if k.startswith(base) and suffix[:3] in k:
                return v
    return None



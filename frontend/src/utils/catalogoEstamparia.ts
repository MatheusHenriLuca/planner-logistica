export function obterEmbalagemEstamparia(material: string | null | undefined): string | undefined {
  if (!material) return undefined;
  if (material.includes("/")) {
    for (const parte of material.split("/")) {
      const res = obterEmbalagemEstamparia(parte.trim());
      if (res) return res;
    }
  }
  const matClean = material.replace(/[^A-Za-z0-9]/g, "").toUpperCase();
  if (CATALOGO_EMBALAGENS_ESTAMPARIA[matClean]) {
    return CATALOGO_EMBALAGENS_ESTAMPARIA[matClean];
  }
  if (matClean.length >= 8) {
    const pref = matClean.slice(0, 8);
    for (const [k, v] of Object.entries(CATALOGO_EMBALAGENS_ESTAMPARIA)) {
      if (k.startsWith(pref)) {
        return v;
      }
    }
  }
  const match = matClean.match(/^([A-Z]\d{4,5})([A-Z].*)$/);
  if (match) {
    const [, base, suffix] = match;
    for (const [k, v] of Object.entries(CATALOGO_EMBALAGENS_ESTAMPARIA)) {
      if (k.startsWith(base) && k.includes(suffix.slice(0, 3))) {
        return v;
      }
    }
  }
  return undefined;
}


export function obterEmbalagemSolda(material: string | null | undefined): string | undefined {
  if (!material) return undefined;
  const matClean = material.trim().toUpperCase();
  if (CATALOGO_EMBALAGENS_SOLDA[matClean]) {
    return CATALOGO_EMBALAGENS_SOLDA[matClean];
  }
  // Tentar casamento por prefixo sem revisão se tiver 10 caracteres
  for (const [cod, emb] of Object.entries(CATALOGO_EMBALAGENS_SOLDA)) {
    if (cod.length >= 8 && matClean.length >= 8 && cod.slice(0, 8) === matClean.slice(0, 8)) {
      return emb;
    }
  }
  return undefined;
}

import { obterEmbalagemEstamparia } from "./catalogoEstamparia";

export function obterEmbalagem(
  material: string | null | undefined,
  setor?: string
): string | undefined {
  if (!material) return undefined;
  if (setor === "estamparia") {
    return obterEmbalagemEstamparia(material) || obterEmbalagemSolda(material);
  }
  return obterEmbalagemSolda(material) || obterEmbalagemEstamparia(material);
}


